const test = require('node:test');
const assert = require('node:assert/strict');
process.env.JWT_SECRET = 'test-secret';
const express = require('express');
const { ZodError } = require('zod');
const { prisma } = require('./helpers/companyMocks.cjs');
const { signToken } = require('../dist/auth');
const rt = require('../dist/realtime'); rt.emitToAdmins = () => {}; rt.emitToDriver = () => {};
const { deliveries } = require('../dist/routes/deliveries');
test('admin delivery corrections preserve prior proof, require authorization and reject stale forms', async () => {
  let d = { id: 'delivery', status: 'PENDING', driverId: 'driver', customerName: 'Cliente', address: 'Rua Teste, 10', product: 'Gas', quantity: 1, lat: -23, lng: -46, notes: 'Antiga', phone: '123', updatedAt: new Date('2026-11-05T12:00:00.000Z'), deliveredAt: null, deliveredLat: null, deliveredLng: null, deliveredDistanceM: null };
  let driverActive = true;
  let conflict = false;
  const history = [];
  let writes = 0;
  const snapshot = value => structuredClone(value);
  prisma.user.findUnique = async ({ where }) => ({ id: where.id, role: where.id === 'admin' ? 'ADMIN' : 'DRIVER', active: true, passwordHash: 'hash' });
  prisma.user.findFirst = async () => driverActive ? { id: 'driver' } : null;
  prisma.user.findMany = async ({ where, select }) => {
    assert.deepEqual(where, { id: { in: ['driver'] }, role: 'DRIVER' });
    assert.deepEqual(select, { id: true, name: true });
    return [{ id: 'driver', name: 'João Entregador' }];
  };
  prisma.delivery.findUnique = async ({ where }) => where.id === 'delivery' ? snapshot(d) : null;
  prisma.delivery.findUniqueOrThrow = async () => snapshot(d);
  prisma.delivery.updateMany = async ({ data }) => {
    if (conflict) return { count: 0 };
    writes++; d = { ...d, ...data, updatedAt: new Date(d.updatedAt.getTime() + 1000) }; return { count: 1 };
  };
  prisma.deliveryChange.create = async ({ data }) => { history.push(data); return data; };
  prisma.deliveryChange.findMany = async () => history;
  prisma.$transaction = async callback => callback(prisma);
  const app = express(); app.use(express.json()); app.use('/deliveries', deliveries);
  app.use((err, req, res, next) => res.status(err instanceof ZodError ? 400 : err.status || 500).json({ error: 'invalid' }));
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const base = `http://127.0.0.1:${server.address().port}/deliveries`;
  const call = (suffix, method, body, role = 'ADMIN') => fetch(base + suffix, { method, headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${signToken({ id: role === 'ADMIN' ? 'admin' : 'driver', role }, 'hash')}` }, ...(body ? { body: JSON.stringify(body) } : {}) });
  try {
    for (const [path, method, body] of [['/delivery', 'PATCH', { customerName: 'Outro' }], ['/delivery/reopen', 'POST', { reason: 'Erro de confirmação' }], ['/delivery/history', 'GET']]) assert.equal((await call(path, method, body, 'DRIVER')).status, 403);
    assert.equal((await call('/missing', 'PATCH', { customerName: 'Outro' })).status, 404);
    for (const body of [{ quantity: 0 }, { customerName: '   ' }, { deliveredAt: new Date().toISOString() }, {}]) assert.equal((await call('/delivery', 'PATCH', body)).status, 400);
    assert.equal((await call('/delivery', 'PATCH', { address: 'Outro endereço' })).status, 400);
    assert.equal((await call('/delivery', 'PATCH', { notes: 'Nova', expectedUpdatedAt: '2026-11-04T12:00:00.000Z' })).status, 409);
    conflict = true;
    assert.equal((await call('/delivery', 'PATCH', { notes: 'Nova' })).status, 409);
    assert.equal(history.length, 0); assert.equal(writes, 0);
    conflict = false;
    assert.equal((await call('/delivery', 'PATCH', { customerName: 'Corrigido', notes: '', phone: '', expectedUpdatedAt: d.updatedAt.toISOString() })).status, 200);
    assert.equal(d.customerName, 'Corrigido'); assert.equal(d.notes, ''); assert.equal(d.phone, '');
    assert.equal(history[0].before.customerName, 'Cliente'); assert.equal(history[0].after.customerName, 'Corrigido'); assert.equal(history[0].actorId, 'admin');
    assert.equal((await call('/delivery/reopen', 'POST', { reason: 'Erro de confirmação' })).status, 409);
    d.status = 'DELIVERED'; d.deliveredAt = new Date('2026-11-05T12:00:00.000Z'); d.deliveredLat = -23; d.deliveredLng = -46; d.deliveredDistanceM = 0;
    assert.equal((await call('/delivery', 'PATCH', { status: 'PENDING' })).status, 409);
    assert.equal((await call('/delivery', 'PATCH', { address: 'Outro endereço', lat: -23, lng: -46 })).status, 409);
    assert.equal((await call('/delivery/reopen', 'POST', { reason: ' ' })).status, 400);
    assert.equal((await call('/delivery/reopen', 'POST', { reason: 'Cliente não recebeu', expectedUpdatedAt: d.updatedAt.toISOString() })).status, 200);
    assert.equal(d.status, 'PENDING'); assert.equal(d.driverId, 'driver'); assert.equal(d.deliveredAt, null); assert.equal(d.deliveredLat, null); assert.equal(d.deliveredLng, null); assert.equal(d.deliveredDistanceM, null);
    assert.equal(history[1].action, 'REOPEN'); assert.equal(history[1].before.deliveredAt, '2026-11-05T12:00:00.000Z'); assert.equal(history[1].before.deliveredLat, -23); assert.equal(history[1].reason, 'Cliente não recebeu');
    assert.equal((await call('/delivery/reopen', 'POST', { reason: 'Cliente não recebeu' })).status, 409);
    assert.equal(history.length, 2);
    d.status = 'CANCELED'; driverActive = false;
    assert.equal((await call('/delivery/reopen', 'POST', { reason: 'Pedido válido novamente' })).status, 200);
    assert.equal(d.driverId, null);
    const response = await call('/delivery/history', 'GET'); assert.equal(response.status, 200); const rows = await response.json(); assert.equal(rows.length, 3);
    assert.equal(rows[0].beforeDriverName, 'João Entregador');
    assert.equal(rows[0].afterDriverName, 'João Entregador');
    assert.equal(rows[2].beforeDriverName, 'João Entregador');
    assert.equal(rows[2].afterDriverName, null);
    assert.equal((await call('/missing/history', 'GET')).status, 404);
    d.status = 'EN_ROUTE';
    assert.equal((await call('/delivery', 'PATCH', { status: 'CANCELED' })).status, 409);
    d.status = 'DELIVERED';
    assert.equal((await call('/delivery', 'PATCH', { status: 'CANCELED' })).status, 409);
    d.status = 'PENDING';
    assert.equal((await call('/delivery', 'PATCH', { status: 'CANCELED' }, 'DRIVER')).status, 403);
    assert.equal((await call('/delivery', 'PATCH', { status: 'CANCELED', expectedUpdatedAt: '2020-01-01T00:00:00.000Z' })).status, 409);
    const previousCount = history.length;
    assert.equal((await call('/delivery', 'PATCH', { status: 'CANCELED', expectedUpdatedAt: d.updatedAt.toISOString() })).status, 200);
    assert.equal(d.status, 'CANCELED');
    assert.equal(history.length, previousCount + 1);
    assert.equal(history.at(-1).before.status, 'PENDING');
    assert.equal(history.at(-1).after.status, 'CANCELED');
    assert.equal(history.at(-1).actorId, 'admin');
  } finally { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await prisma.$disconnect(); }
});

